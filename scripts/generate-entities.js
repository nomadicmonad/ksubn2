function slugToWiki(name){
  const cleaned = name.replace(/\s+/g,'_').replace(/'/g,'%27');
  return `https://en.wikipedia.org/wiki/${cleaned}`;
}

function inferType(name){
  const orgHints=['Agency','Group','Commission','Forum','Foundation','Foundations','Organization','Organisation','Bank','Company','University','Institute','Committee','Council','News','Parliament','Family','House','Department','Program','Project','Lodge','College','NATO','WHO','AIPAC','CIA','NHS','FDA','CDC','BBC','CNN','Reuters','Europol','Interpol'];
  const eventHints=['attack','war','siege','affair','papers','summit','agreement','pandemic','scandal','program','revelations'];
  const n=name.toLowerCase();
  if(eventHints.some(h=>n.includes(h))) return 'event';
  if(orgHints.some(h=>name.includes(h))) return 'organization';
  return 'person';
}

